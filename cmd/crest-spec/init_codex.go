func codexApplySkill() string {
	return `---
name: apply-crest-spec
description: Apply, implement, reconcile, or regenerate a project from its crest-spec. Trigger for requests such as "apply this crest-spec", "run crest-spec", "implement the spec", or "reconcile this project from spec".
---

# Apply crest-spec with Codex

Use this workflow when the user asks Codex to apply the repository's crest-spec. crest-spec is a passive MCP state, planning, persistence, and validation engine. Codex is the orchestrator and must use native Codex subagents for resource work.

## Non-negotiable boundaries

- Use the crest-spec MCP tools. Do not call crest-spec as a generation job CLI and do not expect it to spawn agents.
- Every implementation attempt follows spec/context, then spec/execution_start with crest-execution-v1, then spec/commit by attempt ID. Candidate files never bypass this boundary.
- Run only one crest-spec session at a time in this project.
- Do not edit CUE files after spec/begin. Finish or abandon the session first, then edit, validate, and re-plan.
- Do not write operational manifests, evidence, attempts, or status files into the project. They belong in CrestSpec's SQLite state.
- Do not accept generator self-report as proof. Reconcile every outcome against CrestSpec state and validation records.
- Never call spec/confirm_destroys unless the user has explicitly approved the exact pending resource deletions in the current conversation. The phrase "apply this crest-spec" alone is not deletion approval.
- Never call spec/skip or spec/finish with force without explicit user approval. Repeated failure is not a skip reason.
- Retries are UPDATE-mode repairs. Preserve prior accepted work and use the served error/guidance context.

## Preflight

1. Confirm the crest-spec MCP server and spec tools are available. If they are missing, tell the user to trust the repository and restart the Codex task so project .codex/config.toml is loaded.
2. Inspect git status and preserve unrelated user changes.
3. Run codex --version once and retain the exact output as host_version for execution manifests.
4. The generated custom implementation agents use model gpt-5.6 with high reasoning. Pass that exact model identity to them. If the client cannot select the custom agent and uses a fallback worker, pass the fallback's actual model identity; never falsely record gpt-5.6.

## Plan and begin

1. Call spec/validate. Stop on any structural or project-intent error and report the exact invalid fields.
2. Call spec/project_overview, spec/plan, and spec/plan_inspect. Explain the goals targeted, vertical slices, operation counts, and expected regression checks before beginning.
3. If there is no implementation work, continue to required validation/witness reconciliation instead of declaring completion from an empty resource plan.
4. Call spec/begin and retain its session ID.
5. If PendingDestroys is non-empty, show the exact resources and files, then stop unless the user already approved those exact deletions. After approval, call spec/confirm_destroys with only the returned resource IDs.

## Execute dependency waves with subagents

This skill explicitly requires native Codex subagents. For every wave returned by spec/next:

1. Spawn one crest_generator subagent per resource that still needs work. Dispatch independent resources concurrently up to the available thread limit; if the wave is larger, process it in batches without advancing to the next wave.
2. Give each subagent only one resource and pass session_id, resource_id, the wave's recommended role, max attempts, host_version, actual model/reasoning identity, and current permissions.
3. When the client exposes custom-agent selection, use the project agent crest_generator from .codex/agents/crest-generator.toml. Otherwise spawn a generic worker whose first instruction is to read and follow that file exactly.
4. Wait for every resource in the current wave. Inspect spec/wave_status and state rather than trusting the returned summaries.
5. Call spec/verify_wave only after the wave's candidate attempts are terminally accounted for.
6. On a wave failure, spawn crest_triage agents for independent failure groups. If custom-agent selection is unavailable, use generic workers that read .codex/agents/crest-triage.toml. Apply their evidence-backed spec/resolve guidance, then request the wave again.
7. Halt and report the unresolved resources when the same failure does not converge within the configured retry limits. Do not quietly skip it.

Subagents share the project tree. CrestSpec serializes governed candidate acceptance, but build tools may contend; keep each subagent scoped to one resource and never start a second session.

## Reconcile behavioral evidence

After resource waves are complete:

1. Inspect spec/verification_definitions and project completion state.
2. Spawn one crest_verifier subagent per required or stale witness, concurrently where the commands do not contend. Each verifier must read .codex/agents/crest-verifier.toml when custom-agent selection is unavailable.
3. Re-inspect each run through spec/verification_inspect. Theater, malformed, failed, or stale evidence remains a blocker.
4. If legacy design/task checks are still required, use crest_design and crest_tasks subagents, then verify and graduate only compatible checks. Do not replace stronger named witnesses with weaker legacy observations.

## Finish

1. Re-run spec/project_overview and spec/plan_inspect. Report actual goal progress, missing evidence, regressions, blockers, and attempt failures.
2. Call spec/finish without force. If it refuses, continue only when there is safe in-scope work; otherwise return the exact incomplete goals and required next action.
3. Run the repository's requested final checks only when they add coverage beyond CrestSpec's recorded gates.
4. Commit or push only when the user or repository instructions request it.

Completion means CrestSpec reports the required project goals complete with current evidence. Generated file presence, a green local compile, or a subagent saying "done" is insufficient.
`
}
